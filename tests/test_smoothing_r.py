"""The R-compatible smoothing route, checked against R itself.

A Python port of a published R pipeline is only worth having if it gives the
published numbers. So this compares against reference output generated by the
original R code on 40 real PRISMA spectra, stored in
``tests/data/r_reference/prisma_smoothing.npz``. R is not needed to run these:
its answers are checked in.

The reference was produced by ``stats::smooth.spline`` and
``pracma::findpeaks``, driven by the same four-step core as the user's
``smooth_PRISMA_imagery.R``.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest
import xarray as xr

import hyperproc as hp
from hyperproc.spectral._smoothspline import nknots_smspl, smooth_spline
from hyperproc.spectral.smoothing import PRISMA_ARTEFACT_RANGES, PRISMA_MASK_AFTER, find_spikes

REF = Path(__file__).resolve().parent / "data" / "r_reference" / "prisma_smoothing.npz"


@pytest.fixture(scope="module")
def ref():
    if not REF.is_file():
        pytest.skip(f"no R reference at {REF}")
    return np.load(REF)


def _masked_input(ref, i):
    """One spectrum after steps 1 and 2, using R's own spike mask."""
    wl, spec = ref["wl"], ref["spectra"]
    s = spec[i].copy()
    s[ref["r_spikes"][i]] = np.nan
    drop = np.zeros(wl.size, bool)
    for lo, hi in PRISMA_ARTEFACT_RANGES:
        drop |= (wl >= lo) & (wl <= hi)
    s[drop] = np.nan
    return wl, s


# --------------------------------------------------------------------------- #
# step 1: the peak finder                                                      #
# --------------------------------------------------------------------------- #

def test_find_spikes_is_identical_to_pracma(ref):
    """Bit-for-bit, on every spectrum: this step is pure index logic."""
    got = np.array([find_spikes(s, 0.018) for s in ref["spectra"]])
    assert got.shape == ref["r_spikes"].shape
    assert np.array_equal(got, ref["r_spikes"])
    assert got.sum() > 0


def test_find_spikes_marks_three_bands_per_peak():
    """The peak, where its rise began and where its fall ended. Not the span."""
    x = np.array([0.10, 0.11, 0.12, 0.13, 0.50, 0.14, 0.15, 0.16, 0.155, 0.17, 0.40, 0.18, 0.19])
    assert np.array_equal(np.flatnonzero(find_spikes(x, 0.018)), [0, 4, 5, 8, 10, 11])


def test_find_spikes_respects_the_threshold():
    x = np.array([0.10, 0.11, 0.12, 0.13, 0.50, 0.14, 0.15, 0.16, 0.155, 0.17, 0.40, 0.18, 0.19])
    assert find_spikes(x, 0.018).sum() == 6            # two peaks qualify
    assert find_spikes(x, 1.0).sum() == 0              # none do
    assert find_spikes(x, 0.004).sum() > 6             # the small bump joins in


def test_find_spikes_finds_maxima_only():
    """Downward spikes survive step 1; the header comment says otherwise."""
    dip = np.array([0.3, 0.3, 0.3, 0.05, 0.3, 0.3, 0.3])
    assert not find_spikes(dip, 0.018).any()


def test_find_spikes_on_a_flat_spectrum_is_empty():
    assert not find_spikes(np.linspace(0.1, 0.2, 20), 0.018).any()


