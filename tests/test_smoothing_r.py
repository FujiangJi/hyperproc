@pytest.mark.parametrize("n,expected", [(148, 78), (149, 79), (146, 77), (144, 77), (49, 49)])
def test_nknots_matches_r(n, expected):
    assert nknots_smspl(n) == expected


def test_spline_parameters_match_r(ref):
    """ratio, spar, lambda and df, against R's own reported values."""
    for i in range(ref["spectra"].shape[0]):
        wl, s = _masked_input(ref, i)
        ok = np.isfinite(s)
        fit = smooth_spline(wl[ok], s[ok], df=60)
        assert fit.ratio == pytest.approx(ref["r_ratio"][i], rel=1e-12)
        assert fit.spar == pytest.approx(ref["r_spar"][i], rel=1e-8)
        assert fit.lambda_ == pytest.approx(ref["r_lambda"][i], rel=1e-8)
        assert fit.df == pytest.approx(ref["r_df"][i], rel=1e-8)


def test_spline_at_a_fixed_lambda_matches_r(ref):
    """With the search removed, only the basis and penalty are under test.

    The tolerance is set by floating point, not by the port. R and numpy reach
    LAPACK by different routes, and the fit solves a dense system the size of
    the knot count, so the last couple of digits cannot agree bit for bit.
    Measured on the checked-in reference: median 9e-14, worst band 1.5e-12.
    A failure here means a real change in the basis or the penalty, not drift.
    """
    wl, s = _masked_input(ref, 0)
    ok = np.isfinite(s)
    fit = smooth_spline(wl[ok], s[ok], lam=1e-8)
    assert np.allclose(fit.predict(wl), ref["r_fixed_lambda"], atol=1e-11, rtol=0)
    assert fit.df == pytest.approx(68.5775091301, abs=1e-7)


def test_the_penalty_uses_r_s_constant():
    """R's sgram.f writes the integral of t^2 as 0.3330, not 1/3.

    It looks like a harmless rounding and is not: it shifts the penalty by 1e-3
    relative, which moves lambda and the fitted spectrum. Integrating exactly
    would be more correct and would not reproduce R.
    """
    from hyperproc.spectral._smoothspline import _gram, _knot_vector
    knot = _knot_vector(np.linspace(0, 1, 60), nknots_smspl(60))
    sigma = _gram(knot)
    assert np.allclose(sigma, sigma.T)
    assert np.all(np.diag(sigma) > 0)
    # an exact integral would differ in the fourth digit
    from scipy.interpolate import BSpline
    nk = knot.size - 4
    nodes, weights = np.polynomial.legendre.leggauss(3)
    edges = np.unique(knot)
    half, mid = (edges[1:] - edges[:-1]) / 2, (edges[1:] + edges[:-1]) / 2
    pts = (mid[:, None] + half[:, None] * nodes[None, :]).ravel()
    wts = (half[:, None] * weights[None, :]).ravel()
    d2 = np.column_stack([np.nan_to_num(
        BSpline(knot, np.eye(nk)[j], 3, extrapolate=False).derivative(2)(pts), nan=0.0)
        for j in range(nk)])
    exact = (d2 * wts[:, None]).T @ d2
    rel = abs(np.trace(sigma) - np.trace(exact)) / np.trace(exact)
    assert 1e-4 < rel < 1e-2, f"expected R's 0.3330 to differ from exact by ~1e-3, got {rel:.2e}"


def test_spline_recovers_a_smooth_function():
    """More degrees of freedom follow the curve more closely, as they must."""
    x = np.linspace(400, 2400, 300)
    y = 0.2 + 0.1 * np.sin(x / 300.0)
    errors = [np.abs(smooth_spline(x, y, df=d).predict(x) - y).max() for d in (20, 60, 150)]
    assert errors[0] > errors[1] > errors[2]
    assert errors[-1] < 1e-5


def test_spline_argument_checks():
    x, y = np.linspace(0, 1, 40), np.random.default_rng(0).normal(size=40)
    with pytest.raises(ValueError, match="one of df"):
        smooth_spline(x, y)
    with pytest.raises(ValueError, match="invalid df"):
        smooth_spline(x, y, df=1.0)
    # all-identical x gives IQR 0, so R's tol = 1e-6 * IQR(x) is rejected first
    with pytest.raises(ValueError, match="tol"):
        smooth_spline(np.zeros(10), np.zeros(10), df=3)
    # four distinct values, most of them duplicated, leaves too few unique points
    with pytest.raises(ValueError, match="four unique"):
        smooth_spline(np.array([0.0, 0, 0, 1, 1, 1, 2, 2, 2]), np.arange(9.0), df=3)


