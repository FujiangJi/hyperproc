def _cube(ref):
    wl, spec = ref["wl"], ref["spectra"]
    return xr.Dataset(
        {"reflectance": (("y", "x", "wavelength"),
                         spec.reshape(spec.shape[0], 1, -1).astype("float32"))},
        coords={"wavelength": wl, "y": np.arange(spec.shape[0]), "x": [0]},
        attrs={"sensor": "PRISMA", "stem": "ref"})


def test_pipeline_matches_r(ref):
    out = hp.spline_gapfill(_cube(ref), df=60)
    got = out.reflectance.values.reshape(ref["spectra"].shape[0], -1)
    want = ref["r_smoothed"]
    assert np.array_equal(np.isfinite(got), np.isfinite(want)), "the NaN pattern differs"
    both = np.isfinite(got)
    assert np.abs(got[both] - want[both]).max() < 1e-6


def test_pipeline_masks_exactly_the_published_ranges(ref):
    out = hp.spline_gapfill(_cube(ref), df=60)
    wl = ref["wl"]
    after = np.zeros(wl.size, bool)
    for lo, hi in PRISMA_MASK_AFTER:
        after |= (wl >= lo) & (wl <= hi)
    values = out.reflectance.values.reshape(ref["spectra"].shape[0], -1)
    assert np.isnan(values[:, after]).all()
    assert np.isfinite(values[:, ~after]).all()


def test_pipeline_flags_which_bands_are_spline_fill(ref):
    """The R version does not record this; a reported value may be interpolated."""
    out = hp.spline_gapfill(_cube(ref), df=60)
    assert "spline_filled" in out
    filled = out["spline_filled"].values.reshape(ref["spectra"].shape[0], -1)
    values = out.reflectance.values.reshape(ref["spectra"].shape[0], -1)
    assert filled.any(), "some reported bands are interpolated"
    assert np.isfinite(values[filled]).all(), "a flagged band still carries a value"
    assert not filled[:, ref["wl"] < 500].any()


def test_pipeline_is_lazy_and_keeps_shape(ref):
    ds = _cube(ref).chunk({"y": 8})
    out = hp.spline_gapfill(ds, df=60)
    assert out["reflectance"].chunks is not None
    assert out.sizes == ds.sizes


def test_pipeline_rejects_an_impossible_df(ref):
    with pytest.raises(ValueError, match="df must satisfy"):
        hp.spline_gapfill(_cube(ref), df=1.0)


def test_smooth_spectra_is_untouched_by_all_this(ref):
    """The other smoother keeps its contract: it never fills a gap."""
    ds = _cube(ref)
    out = hp.smooth_spectra(ds, window=5)
    assert np.array_equal(np.isfinite(out.reflectance.values),
                          np.isfinite(ds.reflectance.values))
